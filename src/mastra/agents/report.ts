/**
 * Report Agent — produces the final README.md used both as deliverable
 * documentation and the demo narration script.
 *
 * Runs only after the human approves the review gate.
 */
import { Agent } from '@mastra/core/agent';
import { getModel, cacheProviderOptions } from '../model.js';
import { writeFileTool, readFileTool } from '../tools/fs-tool.js';
import { SUT_BRIEF } from '../context.js';

export const reportAgent = new Agent({
  id: 'report',
  name: 'Report',
  instructions: `
You are a technical writer producing the final README for the delivered test
suite.

${SUT_BRIEF}

## Your job

1. read-file docs/01-test-plan.md, docs/02-architecture.md, docs/03-review.md.

2. Write docs/README.md with these sections (concise, no filler):

   # Moxymind Technical Task — Automated Test Suite

   > Playwright + TypeScript suite for Task 1 (saucedemo UI) and Task 2 (reqres API),
   > generated by an agentic workflow built on Mastra.

   ## Prerequisites
   - Node.js >= 20
   - npm

   ## Setup
   \`\`\`bash
   npm install
   npx playwright install chromium
   \`\`\`

   ## Run the tests
   \`\`\`bash
   npm test              # full suite (ui + api)
   npm run test:ui       # saucedemo only
   npm run test:api      # reqres only
   npm run test:report   # open HTML report
   \`\`\`

   ## Project Structure
   (brief tree of pages/, tests/, data/, src/mastra/)

   ## Test Cases
   For each UI test: name + why essential (one line each)
   For each API test: name + scope (one line each)

   ## The Agentic Workflow (how this suite was built)
   Short description of the 6 agents and the 2 human gates.
   One sentence per agent.

   ## Reviewing & Rebuilding
   \`\`\`bash
   npm run agents        # opens Mastra playground at http://localhost:4111
   \`\`\`
   Explain: start a Brainstorm chat, approve the plan, then run the test-generation
   workflow which auto-runs architect → dev-ui → dev-api → review → report.

   ## Model configuration
   Copy .env.example to .env and set ANTHROPIC_API_KEY. ANTHROPIC_SONNET /
   ANTHROPIC_HAIKU can be overridden to pin different model versions.

3. Reply with: "Delivery complete. README written to docs/README.md."

## Rules
- No marketing fluff. Factual, tight.
- No emoji.
`.trim(),
  model: getModel('reason'),
  defaultOptions: { providerOptions: cacheProviderOptions },
  tools: { writeFileTool, readFileTool },
});
